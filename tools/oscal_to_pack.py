"""Generate a reference pack's model.yaml from a NIST OSCAL control catalog.

Usage::

    python tools/oscal_to_pack.py <catalog.json> <pack-directory>

Writes ``<pack-directory>/model.yaml`` -- the families as ``domain`` nodes and their base
controls as ``control`` nodes, with OSCAL's own identifiers and titles. Nothing else:
control statements, parameters, guidance and enhancements stay in the catalog, because the
pack is a yardstick `align` measures coverage against, and a paraphrase in YAML gets quoted
back as if it were the standard. Withdrawn controls are left out and counted in the header,
so the omission is visible.

Why a script and not a transcription: the reference library's rule is that a taxonomy is
read off its primary source, never written from memory. OSCAL *is* NIST's machine-readable
publication of SP 800-53, so generating from it makes the structure as exact as the source
-- and re-running the script against a later catalog is the whole upgrade procedure. It
does not make the pack *verified*: that word is reserved for a human reading (see the
pack's NOTICE). The NOTICE and SHA256SUMS are written by hand and by `pin-reference`.

Standard library only. The input is untrusted data: it is parsed as JSON, never executed.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path


def _withdrawn(control: dict) -> bool:
    return any(p.get("name") == "status" and p.get("value") == "withdrawn" for p in control.get("props", []))


def _quote(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)  # a JSON string is a valid YAML scalar


def convert(catalog_path: Path, pack_dir: Path) -> tuple[int, int, int]:
    catalog = json.loads(catalog_path.read_text(encoding="utf-8"))["catalog"]
    metadata = catalog["metadata"]
    families = controls = withdrawn = 0
    body: list[str] = []
    for group in catalog["groups"]:
        families += 1
        body += [
            f"  - id: {group['id']}",
            f"    name: {_quote(group['title'])}",
            "    kind: domain",
            f"    externalId: {group['id'].upper()}",
        ]
        for control in group.get("controls", []):
            if _withdrawn(control):
                withdrawn += 1
                continue
            controls += 1
            body += [
                f"  - id: {control['id']}",
                f"    name: {_quote(control['title'])}",
                "    kind: control",
                f"    parent: {group['id']}",
                f"    externalId: {control['id'].upper()}",
            ]
        body.append("")
    header = [
        "# NIST SP 800-53 Revision 5 -- control families and base controls.",
        "#",
        "# Generated by tools/oscal_to_pack.py from NIST's OSCAL catalog, not transcribed:",
        f"#   {metadata['title']}",
        f"#   version {metadata.get('version', '')}, last modified {metadata.get('last-modified', '')}",
        f"# {families} families, {controls} base controls; {withdrawn} withdrawn controls left out.",
        "# Control enhancements, statements, parameters and guidance are deliberately absent --",
        "# the catalog is the authority on what a control requires. Public domain; see NOTICE.md.",
        "",
        "name: NIST SP 800-53 Revision 5",
        f'version: "{metadata.get("version", "")}"',
        f"source: {_quote('NIST OSCAL catalog NIST_SP-800-53_rev5_catalog.json, families and base controls')}",
        "",
        "nodes:",
    ]
    pack_dir.mkdir(parents=True, exist_ok=True)
    text = "\n".join(header + body).rstrip("\n") + "\n"
    (pack_dir / "model.yaml").write_text(text, encoding="utf-8", newline="\n")
    return families, controls, withdrawn


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__.split("\n\n", 2)[1])
        return 2
    families, controls, withdrawn = convert(Path(argv[1]), Path(argv[2]))
    print(f"{families} families, {controls} base controls, {withdrawn} withdrawn left out")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
