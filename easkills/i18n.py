def placeholders(text: str) -> set[str]:
    return {name for _literal, name, _spec, _conv in string.Formatter().parse(text) if name}


def translator(lang: str = DEFAULT) -> Callable[..., str]:
    """``t(key, **values)`` for one language. An unknown language is a caller's error."""
    if lang not in LANGUAGES:
        raise ValueError(f"unknown language '{lang}'; expected one of {', '.join(LANGUAGES)}")

    def t(key: str, **values: object) -> str:
        text = CATALOG[key][lang]
        return text.format(**values) if values else text

    return t
